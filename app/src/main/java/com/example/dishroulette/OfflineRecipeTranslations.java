    static void apply(List<RecipeCatalog.Recipe> recipes) {
        for (int i = 0; i < recipes.size(); i++) {
            RecipeCatalog.Recipe r = recipes.get(i);
            RecipeTranslation en = new RecipeTranslation(), ar = new RecipeTranslation();
            en.title = r.title;
            en.description = r.description;
            en.ingredients = Arrays.asList(r.ingredients.split("\\n"));
            en.steps = new ArrayList<>();
            for (String step : r.method.split("\\n\\n"))
                en.steps.add(step.replaceFirst("^\\d+[.)]\\s*", ""));
            ar.title = AR[i][0];
            ar.description = AR[i][1];
            ar.ingredients = Arrays.asList(AR[i][2].split("\\n"));
            ar.steps = Arrays.asList(AR[i][3].split("\\|"));
            r.translations = RecipeTranslation.validate(Map.of("en", en, "ar", ar));
            r.language = "en";
        }
    }
